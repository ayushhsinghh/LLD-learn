import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const imageRoot = path.join(root, "public/images");
const outputRoot = path.join(imageRoot, "optimized");
const manifestPath = path.join(root, "lib/image-variants.generated.ts");
const args = process.argv.slice(2);
if (args.some((arg) => arg !== "--check") || args.length > 1) {
  throw new Error("Usage: node scripts/generate-image-variants.mjs [--check]");
}
const check = args.includes("--check");
const settings = {
  format: "webp",
  widths: [384, 640, 768, 1024, 1360],
  includeOriginalWidth: true,
  withoutEnlargement: true,
  quality: 85,
  effort: 6,
  kernel: "lanczos3",
  sharp: sharp.versions.sharp,
  vips: sharp.versions.vips,
  webp: sharp.versions.webp,
};
const sha256 = (data) => createHash("sha256").update(data).digest("hex");

async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true }).catch((error) => {
    if (error.code === "ENOENT") return [];
    throw error;
  });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
    const file = path.join(directory, entry.name);
    if (file === outputRoot) continue;
    if (entry.isDirectory()) files.push(...await filesIn(file));
    else if (entry.isFile()) files.push(file);
  }
  return files;
}

const errors = [];
async function saveOrCheck(file, expected) {
  const actual = await readFile(file).catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (actual?.equals(expected)) return;
  if (check) {
    errors.push(`${actual ? "Stale" : "Missing"}: ${path.relative(root, file)}`);
  } else {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, expected);
  }
}

const sources = (await filesIn(imageRoot)).filter((file) => /\.png$/i.test(file));
if (!sources.length) throw new Error("No original PNG images found.");
const manifest = {};
const expectedFiles = new Set();
let originalBytes = 0;
let variantBytes = 0;
let fullWidthBytes = 0;
let candidateCount = 0;

for (const file of sources) {
  const source = await readFile(file);
  const metadata = await sharp(source).metadata();
  const { width, height } = metadata;
  if (!width || !height || (metadata.pages ?? 1) !== 1) {
    throw new Error(`Expected a single image with dimensions: ${file}`);
  }
  const relative = path.relative(imageRoot, file).split(path.sep).join("/");
  const src = `/images/${relative}`;
  const widths = [...new Set([...settings.widths.filter((value) => value <= width), width])].sort((a, b) => a - b);
  const candidates = [];
  for (const candidateWidth of widths) {
    const result = await sharp(source)
      .resize({ width: candidateWidth, withoutEnlargement: settings.withoutEnlargement, kernel: settings.kernel })
      .webp({ quality: settings.quality, effort: settings.effort })
      .toBuffer({ resolveWithObject: true });
    const candidateRelative = relative.replace(/\.png$/i, `-${result.info.width}.webp`);
    const output = path.join(outputRoot, candidateRelative);
    expectedFiles.add(output);
    await saveOrCheck(output, result.data);
    candidates.push({
      src: `/images/optimized/${candidateRelative}`,
      width: result.info.width,
      height: result.info.height,
      bytes: result.data.length,
      sha256: sha256(result.data),
    });
    candidateCount++;
    variantBytes += result.data.length;
    if (result.info.width === width) fullWidthBytes += result.data.length;
  }
  manifest[src] = { width, height, bytes: source.length, sha256: sha256(source), candidates };
  originalBytes += source.length;
}

for (const file of await filesIn(outputRoot)) {
  if (expectedFiles.has(file)) continue;
  if (check) errors.push(`Unexpected: ${path.relative(root, file)}`);
  else await rm(file);
}

const types = `export type ImageVariant = {
  src: string;
  width: number;
  height: number;
  bytes: number;
  sha256: string;
};

export type ImageVariantDefinition = {
  width: number;
  height: number;
  bytes: number;
  sha256: string;
  candidates: readonly ImageVariant[];
};
`;
const content = `// Generated by npm run images:generate. Do not edit by hand.\n// Original PNGs are retained; all URLs are unprefixed public paths.\n\n${types}\nexport const imageVariantSettings = ${JSON.stringify(settings, null, 2)} as const;\n\nexport const imageVariants: Readonly<Record<string, ImageVariantDefinition>> = ${JSON.stringify(manifest, null, 2)};\n`;
await saveOrCheck(manifestPath, Buffer.from(content));
if (errors.length) {
  console.error(errors.join("\n"));
  console.error("Run npm run images:generate to update local variants and their manifest.");
  process.exitCode = 1;
} else {
  console.log(`${check ? "Verified" : "Generated"} ${candidateCount} WebP candidates for ${sources.length} original PNGs.`);
  console.log(`Originals: ${originalBytes} bytes; all variants: ${variantBytes} bytes; full-width WebP: ${fullWidthBytes} bytes (${(100 * (1 - fullWidthBytes / originalBytes)).toFixed(1)}% smaller).`);
}
